"""Build src/content/sources.ts from the citation-checked research report.

Usage: python3 scripts/build-sources.py path/to/report.md
"""
import json
import re
import sys
from pathlib import Path

if len(sys.argv) < 2:
    sys.exit("Usage: python3 scripts/build-sources.py path/to/report.md")
REPORT = Path(sys.argv[1])
OUT = Path(__file__).resolve().parent.parent / "src" / "content" / "sources.ts"
URL = re.compile(r"https?://[^\s)\]]+(?:\([^\s)]*\)[^\s)\]]*)*")
MD_LINK = re.compile(r"\[([^\]]+)\]\((https?://[^\s]+?)\)(?=\s|$|\.)")


def parse_item(text: str) -> dict:
    # Markdown links: keep the URL, drop the bracketed label from the visible text.
    urls = []
    def take_link(m: re.Match) -> str:
        urls.append(m.group(2))
        return ""
    text = MD_LINK.sub(take_link, text)
    # Bare URLs: the first becomes the link; any others stay readable in the text.
    bare = URL.findall(text)
    for u in bare:
        urls.append(u.rstrip("."))
    primary = urls[0] if urls else ""
    for u in bare:
        if u.rstrip(".") == primary:
            text = text.replace(u, "")
        else:
            short = re.sub(r"^https?://(www\.)?", "", u.rstrip("."))
            short = short.replace("doi.org/", "doi:")
            text = text.replace(u, f"({short})")
    # Notes the checker left for the editor, not for readers.
    text = re.sub(r",?\s*\d+[–-]\d+\s*\[page range to confirm\]", "", text)
    text = re.sub(r"\s*\[[^\]]*to confirm[^\]]*\]", "", text)
    text = re.sub(r"\s+and\s*$", "", text.strip())
    text = re.sub(r"\.\s+and\s+\(", " (", text)
    text = re.sub(r"\s{2,}", " ", text).strip()
    text = re.sub(r"\s+([.,;])", r"\1", text)
    text = re.sub(r"\.\s*\.$", ".", text)
    return {"text": text, "url": primary}


def main() -> None:
    src = REPORT.read_text()
    refs = src[src.index("## References"):]
    groups, cur = [], None
    for line in refs.splitlines():
        if line.startswith("### "):
            cur = {"title": line[4:].strip(), "items": []}
            groups.append(cur)
            continue
        m = re.match(r"^(\d+)\. (.*)$", line)
        if m and cur is not None:
            cur["items"].append({"n": int(m.group(1)), **parse_item(m.group(2).strip())})
    # Outreach sources are strategy notes, not evidence for the model.
    public = [g for g in groups if not g["title"].startswith("Amplifier")]
    for g in public:
        g["id"] = re.sub(r"[^a-z0-9]+", "-", g["title"].lower()).strip("-")
    header = (
        "// Generated by scripts/build-sources.py from reports/Figure of eight evidence base.md\n"
        "// (citation-checked 3 October 2026). Regenerate rather than hand-edit; numbers match the report.\n\n"
        "export type Source = { n: number; text: string; url: string };\n"
        "export type SourceGroup = { id: string; title: string; items: Source[] };\n\n"
        'export const sourcesCheckedOn = "2026-10-03";\n\n'
    )
    OUT.write_text(header + "export const sourceGroups: SourceGroup[] = " + json.dumps(public, ensure_ascii=False, indent=2) + ";\n")
    total = sum(len(g["items"]) for g in public)
    print(f"{len(public)} groups, {total} sources -> {OUT}")


if __name__ == "__main__":
    main()
